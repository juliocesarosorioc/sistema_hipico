-- ===========================================================================
-- CUADERNO DE JUGADAS POR CLIENTE (libro manual, entre varios grupos)
-- ===========================================================================
-- QUE RESUELVE
-- El admin anota a mano las jugadas de un cliente repartidas entre VARIOS
-- grupos, incluidos grupos que NO están registrados en el sistema (un amigo,
-- una agencia externa, un "grupo" de palabra). El Cuaderno da, por cliente:
--   · totales jugados / premios / neto / pendiente,
--   · el balance POR GRUPO, y
--   · el balance POR SEMANA (lunes a domingo).
--
-- QUE NO HACE (a propósito)
--   - NO crea tickets ni toca `tickets_apuestas`.
--   - NO mueve saldo, aval ni caja. Es un libro de control, no una venta.
--   Liquidar de verdad sigue siendo el módulo de Liquidación / Taquilla.
--   Por eso el Cuaderno es seguro: equivocarse acá no descuadra la caja.
--
-- POR QUE UNA TABLA NUEVA Y NO REUSAR tickets_apuestas
--   tickets_apuestas exige cliente_id REAL, grupo_cobro_id REAL y descuenta
--   saldo al insertarse. El requisito es lo contrario: grupos que no existen
--   en `grupos_venta` y sin efecto sobre saldos. Forzarlo en tickets_apuestas
--   obligaría a inventar grupos y a tocar saldos: exactamente lo que NO se
--   pidió. Por eso `grupo_id` es NULLABLE y `grupo_nombre` es TEXTO LIBRE.
--
-- IDEMPOTENCIA. Aplicarlo varias veces no cambia nada.
-- Ejecutar en el SQL Editor de Supabase.
-- ===========================================================================

begin;

-- ---------------------------------------------------------------------------
-- 1) Tabla
-- ---------------------------------------------------------------------------
create table if not exists public.cuaderno_jugadas (
  id            bigint generated by default as identity primary key,
  -- Dueño del apunte. Borrar al cliente se lleva su cuaderno (on delete cascade).
  cliente_id    uuid not null references public.clientes(id) on delete cascade,
  -- Grupo REGISTRADO (opcional). NULL cuando el grupo no existe en el sistema.
  grupo_id      uuid references public.grupos_venta(id) on delete set null,
  -- Nombre del grupo SIEMPRE presente: es la clave de agrupación del reporte,
  -- exista o no en `grupos_venta`. No se deriva de grupo_id a propósito, para
  -- que renombrar un grupo no reescriba el histórico del cuaderno.
  grupo_nombre  text not null,
  -- Fecha del apunte = fecha de la CARRERA de esa jugada (no la de carga).
  -- Los reportes semanales (lunes a domingo) se arman con esta columna.
  fecha         date not null default current_date,
  hipodromo     text,
  carrera       integer,
  -- Tipo/nombre de la jugada ("GANADOR", "EXACTA", "5Y6", etc.). Texto libre.
  tipo          text not null default 'JUGADA',
  caballo       text,
  monto         numeric not null default 0,
  -- Premio SOLO se tiene en cuenta cuando estado = 'Ganada'.
  premio        numeric not null default 0,
  estado        text not null default 'Pendiente',
  nota          text,
  creado_por    text,
  created_at    timestamptz not null default now(),
  constraint cuaderno_jugadas_estado check (estado in ('Pendiente', 'Ganada', 'Perdida', 'Reembolsada')),
  constraint cuaderno_jugadas_monto  check (monto  >= 0),
  constraint cuaderno_jugadas_premio check (premio >= 0)
);

-- Si la tabla venía de una corrida anterior a medias, se completa lo que falte
-- en vez de fallar: `create table if not exists` es un mentiroso cuando la
-- forma no coincide.
alter table public.cuaderno_jugadas add column if not exists grupo_id     uuid references public.grupos_venta(id) on delete set null;
alter table public.cuaderno_jugadas add column if not exists grupo_nombre text;
alter table public.cuaderno_jugadas add column if not exists hipodromo    text;
alter table public.cuaderno_jugadas add column if not exists carrera      integer;
alter table public.cuaderno_jugadas add column if not exists tipo         text not null default 'JUGADA';
alter table public.cuaderno_jugadas add column if not exists caballo      text;
alter table public.cuaderno_jugadas add column if not exists monto        numeric not null default 0;
alter table public.cuaderno_jugadas add column if not exists premio       numeric not null default 0;
alter table public.cuaderno_jugadas add column if not exists estado       text not null default 'Pendiente';
alter table public.cuaderno_jugadas add column if not exists nota         text;
alter table public.cuaderno_jugadas add column if not exists creado_por   text;
alter table public.cuaderno_jugadas add column if not exists created_at   timestamptz not null default now();

-- grupo_nombre es NOT NULL en el uso real; si una fila vieja quedó en NULL se
-- normaliza a 'SIN GRUPO' para que el agrupamiento nunca cuelgue.
update public.cuaderno_jugadas set grupo_nombre = 'SIN GRUPO' where grupo_nombre is null;
alter table public.cuaderno_jugadas alter column grupo_nombre set not null;

create index if not exists cuaderno_jugadas_cliente_fecha_idx
  on public.cuaderno_jugadas (cliente_id, fecha desc);

create index if not exists cuaderno_jugadas_grupo_fecha_idx
  on public.cuaderno_jugadas (grupo_nombre, fecha desc);

-- ---------------------------------------------------------------------------
-- 2) RLS + PERMISOS
-- El rol real de la SPA es `authenticated` (hay login real). `anon` NO lee ni
-- escribe: el cuaderno es información de la casa. El alcance por grupo lo
-- aplica la app (el apunte cuelga de un cliente, que ya está aislado por RLS).
-- ---------------------------------------------------------------------------
alter table public.cuaderno_jugadas enable row level security;

drop policy if exists cuaderno_jugadas_publico on public.cuaderno_jugadas;
create policy cuaderno_jugadas_publico on public.cuaderno_jugadas
  for all to authenticated
  using (true) with check (true);

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.cuaderno_jugadas to authenticated, service_role;
grant usage, select on sequence public.cuaderno_jugadas_id_seq to authenticated, service_role;

commit;


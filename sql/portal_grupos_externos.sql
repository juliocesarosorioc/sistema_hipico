-- ===========================================================================
-- BITÁCORA PERSONAL DEL PORTAL: GRUPOS Y JUGADAS EN OTROS GRUPOS EXTERNOS
--                      (PROMPT #7 — ítem 1)
-- ===========================================================================
-- QUE RESUELVE
-- El usuario del Portal también juega en grupos que NO están en la plataforma
-- (un amigo, una agencia, un "grupo" de palabra). Este par de tablas le da su
-- libro de control PRIVADO: crea grupos externos (nombre, moneda, % de
-- comisión) y anota jugadas con fecha, hipódromo, carrera, tipo de jugada,
-- ejemplares, monto y estado (PENDIENTE / GANÓ / PERDIÓ / ANULADA).
--
-- QUE NO HACE (y esto es lo importante)
--   - NO crea tickets ni toca `tickets_apuestas`.
--   - NO mueve saldo, aval, caja, devoluciones ni ningún reporte de los grupos
--     oficiales: no hay triggers, vistas ni claves foráneas hacia
--     `grupos_venta`, `tickets_*`, `cuaderno_jugadas` o las cajas. Anotar acá
--     es exactamente tan inocente como anotar en un cuaderno de papel.
--   - NO la ve nadie más: RLS habilitado y SIN políticas → ni `anon` ni
--     `authenticated` leen ni escriben; solo la Edge Function `portal-auth`
--     (service_role) accede, y siempre anclada al cliente de su token.
--
-- QUIÉN ESCRIBE
-- Solo la Edge Function `supabase/functions/portal-auth` con las acciones
-- `grupos-externos` y `jugada-externa`. La SPA no tiene llave para esto.
--
-- IDEMPOTENCIA. Aplicarlo varias veces no cambia nada.
-- Ejecutar en el SQL Editor de Supabase.
-- ===========================================================================

begin;

-- ---------------------------------------------------------------------------
-- 1) Tabla: grupos externos del usuario
-- ---------------------------------------------------------------------------
create table if not exists public.portal_grupos_externos (
  id            bigint generated by default as identity primary key,
  -- Dueño del grupo. Borrar al cliente se lleva su bitácora entera.
  cliente_id    uuid not null references public.clientes(id) on delete cascade,
  -- Nombre propio del grupo ("EL CLUB DE JUAN"), texto libre en MAYÚSCULAS.
  nombre        text not null,
  -- Moneda en la que se juega en ese grupo (USD, VES…).
  moneda        text not null default 'USD',
  -- % de comisión que se lleva ese grupo (0 a 100). Define el premio:
  -- premio = monto x (2 - comision/100), es decir el par menos la comisión.
  comision_pct  numeric not null default 0,
  creado_at     timestamptz not null default now(),
  constraint portal_grupos_externos_comision check (comision_pct >= 0 and comision_pct <= 100),
  -- Un mismo cliente no puede tener dos grupos con el mismo nombre: es la
  -- clave con la que él identifica sus propios grupos en la UI.
  constraint portal_grupos_externos_nombre_unico unique (cliente_id, nombre)
);

create index if not exists portal_grupos_externos_cliente_idx
  on public.portal_grupos_externos (cliente_id, nombre);

-- ---------------------------------------------------------------------------
-- 2) Tabla: jugadas anotadas en un grupo externo
-- ---------------------------------------------------------------------------
create table if not exists public.portal_jugadas_externas (
  id                bigint generated by default as identity primary key,
  -- Doble ancla: el dueño y el grupo. Borrar el grupo se lleva sus jugadas
  -- (cascade), borrar al cliente se lleva las dos cosas.
  cliente_id        uuid not null references public.clientes(id) on delete cascade,
  grupo_externo_id  bigint not null references public.portal_grupos_externos(id) on delete cascade,
  -- Fecha de la CARRERA (no de carga): es la que ordena el libro.
  fecha             date not null default current_date,
  hipodromo         text,
  carrera           integer,
  -- Tipo/nombre de la jugada ("JUGADA", "EXACTA", "TRIO"…). Texto libre.
  tipo_jugada       text not null default 'JUGADA',
  -- Ejemplares involucrados, texto libre ("1-5 EL MAGO, 8 REYAZUL").
  ejemplares        text,
  monto             numeric not null default 0,
  estado            text not null default 'PENDIENTE',
  creado_at         timestamptz not null default now(),
  constraint portal_jugadas_externas_estado check (estado in ('PENDIENTE', 'GANÓ', 'PERDIÓ', 'ANULADA')),
  constraint portal_jugadas_externas_monto  check (monto >= 0),
  constraint portal_jugadas_externas_carrera check (carrera is null or carrera >= 0)
);

-- El libro se recorre por grupo y por fecha descendente.
create index if not exists portal_jugadas_externas_grupo_fecha_idx
  on public.portal_jugadas_externas (grupo_externo_id, fecha desc, id desc);
create index if not exists portal_jugadas_externas_cliente_idx
  on public.portal_jugadas_externas (cliente_id, fecha desc);

-- ---------------------------------------------------------------------------
-- 3) RLS + PERMISOS — cerrado para todos, abierto solo para service_role
-- A diferencia de otras tablas del proyecto (que sí dan acceso a
-- `authenticated`), ACÁ NADIE más que la Edge Function toca los datos: son
-- datos personales de un cliente visto desde su portal. RLS habilitado y SIN
-- políticas = denegación total para anon y authenticated, porque una policy es
-- lo único que permite leer. El service_role, por definición, ignora RLS.
-- ---------------------------------------------------------------------------
alter table public.portal_grupos_externos enable row level security;
alter table public.portal_jugadas_externas enable row level security;

-- (A propósito no se crea ninguna policy. No hace falta "drop" de policies
--  viejas: nunca se crearon.)

-- El grant de esquema es inofensivo con RLS sin policies (no hay policy que
-- habilite nada), y evita "permission denied" de esquema raro en el camino de
-- service_role.
grant usage on schema public to authenticated;

commit;

